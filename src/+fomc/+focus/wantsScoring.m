function tf = wantsScoring(question)
%WANTSSCORING True when a question asks for numeric scoring of FOMC minutes.
%   tf = fomc.focus.wantsScoring(question)

q = lower(string(question));
explicitPatterns = [ ...
    "(?<![a-z])scor(e|es|ed|ing)(?![a-z])", ...
    "(?<![a-z])(hawk|dov)ish(ness)?(?![a-z])", ...
    "(?<![a-z])(grade|quantify|measure)(?![a-z])", ...
    "(?<![a-z])rate\s+(the|this|these).*?(minutes|tone|stance)(?![a-z])", ...
    "(?<![a-z])numeric(ally)?(?![a-z])", ...
    "-1\s*(to|and)\s*\+?1", ...
    "(?<![a-z])on a scale(?![a-z])" ];
if anyMatch(q, explicitPatterns)
    tf = true;
    return
end

topicPatterns = [ ...
    "(?<![a-z])(inflation|prices?)(?![a-z])", ...
    "(?<![a-z])(labor market|employment|wages?|unemployment)(?![a-z])", ...
    "(?<![a-z])(economic activity|growth|spending|output)(?![a-z])", ...
    "(?<![a-z])(financial conditions|credit|markets?)(?![a-z])", ...
    "(?<![a-z])balance sheet(?![a-z])", ...
    "(?<![a-z])risk balance(?![a-z])", ...
    "(?<![a-z])(rate path|policy rates?|interest rates?)(?![a-z])" ];
asksToneOrStance = ~isempty(regexp(q, "(?<![a-z])(tone|stance)(?![a-z])", "once"));
if asksToneOrStance && anyMatch(q, topicPatterns)
    tf = false;
    return
end

patterns = [ ...
    "(?<![a-z])compare.*?(meetings?|fed|fomc|stance|scores?)(?![a-z])" ];
if anyMatch(q, patterns)
    tf = true;
    return
end

globalTonePatterns = [ ...
    "(?<![a-z])(?:overall|general|aggregate)\s+(?:tone|stance)(?![a-z])", ...
    "(?<![a-z])(?:tone|stance)\s+(?:of|in|across)\s+(?:the\s+)?(?:fomc\s+)?(?:minutes|meeting|committee)(?![a-z])", ...
    "(?<![a-z])(?:fomc|fed)(?:'s)?\s+(?:overall\s+)?(?:tone|stance)(?![a-z])" ];
tf = anyMatch(q, globalTonePatterns);
end

function tf = anyMatch(q, patterns)
% True if any pattern matches. regexp returns a cell array for several patterns but not for one
% in R2026b, so each is tried on its own.
tf = any(arrayfun(@(p) ~isempty(regexp(q, p, "once")), patterns));
end
